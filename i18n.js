  const STORAGE_KEY = "kc_lang";

  function getLang() {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored === "bn" || stored === "en") return stored;
    } catch (_) { /* localStorage blocked */ }
    return "bn"; // বাংলা ডিফল্ট
  }

  function setLang(lang) {
    if (lang !== "bn" && lang !== "en") return;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (_) {}
    applyTranslations(lang);
    document.documentElement.setAttribute("lang", lang);
  }

  function t(key, replacements) {
    const lang = getLang();
    let text = translations[lang][key] || translations.bn[key] || key;
    if (replacements) {
      Object.keys(replacements).forEach(k => {
        text = text.replace("{" + k + "}", replacements[k]);
      });
    }
    return text;
  }

  function applyTranslations(lang) {
    const dict = translations[lang] || translations.bn;
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if (dict[key]) el.textContent = dict[key];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      if (dict[key]) el.setAttribute("placeholder", dict[key]);
    });
    // ভাষা toggle বাটনের লেবেল আপডেট
    const toggle = document.getElementById("langToggle");
    if (toggle) toggle.textContent = lang === "bn" ? "EN" : "বাং";
  }

  function init() {
    const lang = getLang();
    document.documentElement.setAttribute("lang", lang);
    if (document.readyState === "loading") {
      document.addEventListener("DOMContentLoaded", () => applyTranslations(lang));
    } else {
      applyTranslations(lang);
    }
    const toggle = document.getElementById("langToggle");
    if (toggle) {
      toggle.addEventListener("click", () => {
        setLang(getLang() === "bn" ? "en" : "bn");
      });
    }
  }

  window.KC_i18n = { t, getLang, setLang, applyTranslations };
  init();
